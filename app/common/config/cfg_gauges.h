#define CFG_SPEED_MAX_KMH               180u    /**< 车速最大显示值（kmh）                          */
#define CFG_SPEED_SEATBELT_WARN_KMH     5u      /**< 安全带报警触发的最低车速（kmh）                */

/*===========================================================================
 *  转速参数 (Section 9.2)
 *===========================================================================*/
#define CFG_RPM_MAX                     8000u   /**< 最大显示转速（r/min）        */
#define CFG_RPM_RED_ZONE                6000u   /**< 红区起始转速（r/min）        */
#define CFG_RPM_CHARGER_NO_SPEED        350u    /**< 判定"已起机"的最低转速        */

/*===========================================================================
 *  燃油参数 (Section 8.1)
 *===========================================================================*/
#define CFG_FUEL_TANK_LARGE_L           45u     /**< 大油箱容量（L）              */
#define CFG_FUEL_TANK_SMALL_L           15u     /**< 小油箱容量（L）              */
#define CFG_FUEL_OPEN_OHMS              360u    /**< 油位传感器开路判定阈值（Ω）  */
#define CFG_FUEL_SHORT_OHMS             10u     /**< 油位传感器短路判定阈值（Ω）  */
#define CFG_FUEL_FAULT_HOLD_MS          20000u  /**< 故障判定持续时间（ms）：进入故障态前需持续保持异常 */
#define CFG_FUEL_RECOVERY_MS            5000u   /**< 故障恢复持续时间（ms）：返回正常态前需持续保持正常 */
#define CFG_FUEL_SEGMENTS               9u      /**< 油量显示总格数              */
#define CFG_FUEL_WARN_SEGMENT           2u      /**< 低油量报警阈值格数（≤该值触发闪烁）*/

/*===========================================================================
 *  水温参数 (Section 8.4)
 *===========================================================================*/
#define CFG_COOLANT_WARN_SEGMENT        8u      /**< 水温报警起始格数（达到此格触发高温警告）   */
#define CFG_COOLANT_MAX_SEGMENT         9u      /**< 水温最大显示格数                            */
#define CFG_COOLANT_TIMEOUT_S           1u     /**< 水温信号丢失超时时间（秒）                  */
#define CFG_COOLANT_TEMP_WARN_C         113     /**< 高温报警进入阈值（℃）                       */
#define CFG_COOLANT_TEMP_WARN_CLEAR_C   110     /**< 高温报警解除阈值（℃，迟滞）                  */

/*===========================================================================
 *  里程参数 (Section 8.5)
 *===========================================================================*/
#define CFG_ODO_MAX_KM                  999999u /**< 总里程上限（km）                                */
#define CFG_TRIP_MAX_DM                 9999u   /**< 小计里程上限（0.1km 精度，= 999.9km）           */
#define CFG_TRIP_CLEAR_RESIST_OHM       8900u   /**< 方向盘 OK 键对应电阻（Ω），用于清零小计里程     */
#define CFG_TRIP_CLEAR_HOLD_MS          3000u   /**< OK 键持续按压清零的时间阈值（ms）               */

/*===========================================================================
 *  胎压参数 (Section 8.3)
 *===========================================================================*/
#define CFG_TPMS_MAX_PRESSURE_KPA       990u    /**< 胎压显示上限（kPa），超出时按上限显示  */

/*===========================================================================
 *  车外温度参数 (Section 9.3)
 *===========================================================================*/
#define CFG_AMBIENT_TEMP_OPEN_KOHM      1500u   /**< 外温传感器开路判定阈值（kΩ）                  */
#define CFG_AMBIENT_TEMP_SHORT_KOHM_X10 1u      /**< 外温传感器短路判定阈值（kΩ × 10，即 0.1kΩ）   */
#define CFG_AMBIENT_UPDATE_S            10u     /**< 外温更新周期（秒）                              */
#define CFG_AMBIENT_OFFSET              40      /**< 外温外发偏移（℃），CAN 编码 = temp + offset   */

/*===========================================================================
 *  背光参数
 *===========================================================================*/
/**
 * 小灯（位置灯 / A8）亮起时的背光亮度百分比。
 *
 * ⚠ 保持原工程取值 60u 不变。需求文字"降低亮度 40%"有两种读法：
 *     降低 40%（剩 60%）→ 60u  （当前取值 = 原工程）
 *     降到 40%          → 40u
 *   与客户确认后再改这一个数字，改动范围仅此一行。
 */
#define CFG_BACKLIGHT_DIM_PERCENT       80u     /**< 小灯亮起时的背光亮度（%） */

/*===========================================================================
 *  充电指示灯延迟（Section 6.x）
 *===========================================================================*/
#define CFG_CHARGER_DELAY_NO_RPM_MS     1000u   /**< 起机前判定时间（ms） */
#define CFG_CHARGER_DELAY_WITH_RPM_MS   3000u   /**< 起机后判定时间（ms） */

/*===========================================================================
 *  机油压力指示灯延迟
 *===========================================================================*/
#define CFG_OIL_PRESS_DELAY_MS          2000u   /**< 机油压力低判定延迟（ms） */

/** 外温 NTC 是否接入。本仪表 ADC 序列无外温通道，置 0：
 *  AMBIENT_Task 恒置无效 → 液晶显示无效态、0x381 的 Ambient_Temp 发 0xFF。
 *  将来接入外温传感器时改为 1，并同步扩展 ADC 序列与 ADC_CHANNEL_COUNT。 */
#define CFG_AMBIENT_SENSOR_PRESENT      0

#endif /* CLUSTER_CFG_GAUGES_H */