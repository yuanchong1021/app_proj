/**
 * @file    cfg_lcd_addr.h
 * @brief   LCD 段码屏地址映射表
 *
 * 修改影响范围：app/ui/lcd_ui.c、driver/lcd_seg/
 *
 * 地址规划：
 *   0x00 ~ 0x0F   燃油 / CNG 区域（9 格 + 2 图标）
 *   0x10 ~ 0x1F   水温区域（9 格）
 *   0x20 ~ 0x2F   胎压区域（4 轮 × 3 位数字 + 4 个轮胎图标）
 *   0x40 ~ 0x47   里程区域（6 位数字 + 2 个文字标签）
 *   0x50 ~ 0x54   外温区域（3 位数字 + 负号 + ℃ 符号）
 *
 * 每个地址对应一个独立可控的段（或位置）。
 * 实际 COM/SEG 引脚映射在 driver/lcd_seg/lcd_seg_drv.c 的 LCD_AddrToReg() 中配置。
 */

#ifndef CLUSTER_CFG_LCD_ADDR_H
#define CLUSTER_CFG_LCD_ADDR_H

/*---------------------------------------------------------------------------
 *  燃油 / CNG 区域
 *---------------------------------------------------------------------------*/
#define LCD_SEG_FUEL_BASE       0x00u   /**< 燃油格起始地址：F1=0x00, F2=0x01, ..., F9=0x08 */
#define LCD_SEG_FUEL_ICON       0x09u   /**< 油泵图标                         */
#define LCD_SEG_CNG_ICON        0x0Au   /**< CNG 字样图标（与油泵图标互斥）   */

/*---------------------------------------------------------------------------
 *  水温区域
 *---------------------------------------------------------------------------*/
#define LCD_SEG_COOLANT_BASE    0x10u   /**< 水温格起始地址：T1=0x10, T2=0x11, ..., T9=0x18 */

/*---------------------------------------------------------------------------
 *  胎压区域（每个轮胎占 3 位数字 + 1 个图标）
 *---------------------------------------------------------------------------*/
#define LCD_SEG_TPMS_LF_BASE    0x20u   /**< 左前胎压数字（百/十/个，共 3 位） */
#define LCD_SEG_TPMS_RF_BASE    0x23u   /**< 右前胎压数字                       */
#define LCD_SEG_TPMS_LR_BASE    0x26u   /**< 左后胎压数字                       */
#define LCD_SEG_TPMS_RR_BASE    0x29u   /**< 右后胎压数字                       */
#define LCD_SEG_TIRE_LF         0x2Cu   /**< 左前轮胎图标                       */
#define LCD_SEG_TIRE_RF         0x2Du   /**< 右前轮胎图标                       */
#define LCD_SEG_TIRE_LR         0x2Eu   /**< 左后轮胎图标                       */
#define LCD_SEG_TIRE_RR         0x2Fu   /**< 右后轮胎图标                       */

/*---------------------------------------------------------------------------
 *  里程区域
 *---------------------------------------------------------------------------*/
#define LCD_SEG_ODO_BASE        0x40u   /**< 里程数字起始地址（6 位，高位在低地址） */
#define LCD_SEG_ODO_LABEL       0x46u   /**< "ODO"  文字标签                    */
#define LCD_SEG_TRIP_LABEL      0x47u   /**< "TRIP" 文字标签                    */

/*---------------------------------------------------------------------------
 *  车外温度区域
 *---------------------------------------------------------------------------*/
#define LCD_SEG_AMBIENT_BASE    0x50u   /**< 外温数字起始地址（3 位） */
#define LCD_SEG_AMBIENT_SIGN    0x53u   /**< 负号 "−" 段              */
#define LCD_SEG_AMBIENT_UNIT    0x54u   /**< "°C" 单位符号            */

/*---------------------------------------------------------------------------
 *  段码常量
 *---------------------------------------------------------------------------*/
#define LCD_SEG_ON              (0xFFu)     /**< 段点亮                     */
#define LCD_SEG_OFF             (0x00u)     /**< 段熄灭                     */
#define LCD_NUM_INVALID         (0xFFFFu)   /**< 数值无效，显示 "---"        */

#endif /* CLUSTER_CFG_LCD_ADDR_H */
